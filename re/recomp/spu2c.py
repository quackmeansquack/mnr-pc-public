"""Ahead-of-time compiler for the SPU programs embedded in the EBOOT.

Each program becomes one C function: every instruction gets a label and a call
`spu_exec(s, <word>, <pc>)` (spu_core.h, always inlined), so Clang constant-folds the decoding. After
each instruction the generated code falls through if the PC moved on by 4, and otherwise re-dispatches
through a switch over all instruction addresses (branches, calls, returns). A PC outside the program
returns to the runner.

Programs:
- SPURS task ELFs (machine 0x17) found in the EBOOT, named by their guest address: the executable
  segments at their ELF load addresses.
- SPURS job binaries ("jobbin2"), named `job:<guest address>:<size>`: position-independent code that
  spu_run_job (spu.c) loads at LS 0x1000 (JOB_BIN).

Output: out/spu_p_<addr>.c per program and out/spu_progs.c with the table {guest address, function}.

Usage: python -I spu2c.py <EBOOT.elf> <out dir> [elf_va_hex | job:va_hex:size_hex ...]   (default: the
skin/morph tasks and the Wwise audio jobs)"""
import os
import struct
import sys

JOB_BIN = 0x1000
DEFAULT = ['f18580', 'f19e80', 'f1b680', 'f1d880',
           # qTask programs run in place of their PPU versions (SceneModel, OcclusionCull, KartTrackScene, TrackView)
           'f00480', 'f1f180', 'efb380', 'eec980', 'f0d880', 'ef5100', 'edd680', 'f38780', 'f2e400', 'f28180',
           # Wwise jobs seen in the first race (binary address : size in bytes)
           'job:e51a00:490', 'job:e51100:110', 'job:e70500:4c10', 'job:e67c00:88a0', 'job:e54a00:1b10',
           'job:e52d00:910', 'job:e54180:810', 'job:e7b100:f10', 'job:e58a00:1f10', 'job:e66200:1990',
           'job:e5e100:2610', 'job:e7a800:890', 'job:e64a80:1710', 'job:e75180:4590']


def segments(d):
    phoff, = struct.unpack_from('>Q', d, 0x20)
    phnum, = struct.unpack_from('>H', d, 0x38)
    for i in range(phnum):
        t, fl, off, va, pa, fs, ms, al = struct.unpack_from('>IIQQQQQQ', d, phoff + i * 0x38)
        if t == 1:
            yield off, va, fs


def file_offset(d, va):
    for off, sva, fs in segments(d):
        if sva <= va < sva + fs:
            return off + va - sva
    raise ValueError(f'0x{va:x} is not in a loadable segment')


def elf_insns(d, foff):
    e_phoff, = struct.unpack_from('>I', d, foff + 0x1C)
    e_phnum, = struct.unpack_from('>H', d, foff + 0x2C)
    insns = []
    for i in range(e_phnum):
        t, off, va, pa, fsz, msz, fl, al = struct.unpack_from('>8I', d, foff + e_phoff + i * 32)
        if t != 1 or not (fl & 1):
            continue
        for a in range(0, fsz & ~3, 4):
            insns.append((va + a, struct.unpack_from('>I', d, foff + off + a)[0]))
    return insns


def emit(name, insns):
    lines = ['/* Generated by spu2c.py */', '#include "spu_core.h"', '#pragma clang diagnostic ignored "-Wunused-label"', '',
             f'void {name}(spu_t *s) {{', '  for (;;) {', '    switch (s->pc) {']
    lines += [f'    case 0x{pc:x}: goto L_{pc:x};' for pc, _ in insns]
    lines += ['    default: return;', '    }']
    for k, (pc, w) in enumerate(insns):
        nxt = insns[k + 1][0] if k + 1 < len(insns) else None
        fall = f'if (s->pc != 0x{nxt:x}) continue;' if nxt is not None else 'continue;'
        lines.append(f'L_{pc:x}: if (!spu_exec(s, 0x{w:08x}u, 0x{pc:x})) return; {fall}')
    lines += ['  }', '}', '']
    return '\n'.join(lines)


def main():
    eboot, outdir = sys.argv[1], sys.argv[2]
    d = open(eboot, 'rb').read()
    table = []
    for spec in sys.argv[3:] or DEFAULT:
        if spec.startswith('job:'):
            _, va, size = spec.split(':')
            va, size = int(va, 16), int(size, 16)
            off = file_offset(d, va)
            insns = [(JOB_BIN + a, struct.unpack_from('>I', d, off + a)[0]) for a in range(0, size & ~3, 4)]
        else:
            va = int(spec, 16)
            off = file_offset(d, va)
            if d[off:off + 4] != b'\x7fELF' or struct.unpack_from('>H', d, off + 0x12)[0] != 0x17:
                raise ValueError(f'no SPU ELF at 0x{va:x}')
            insns = elf_insns(d, off)
        name = f'spu_prog_{va:08x}'
        path = os.path.join(outdir, f'spu_p_{va:08x}.c')
        src = emit(name, insns)
        if not os.path.exists(path) or open(path).read() != src:   # keep the mtime when unchanged
            open(path, 'w').write(src)
        table.append((va, name))
    lines = ['/* Generated by spu2c.py: SPU programs compiled ahead of time (see spu_core.h). */', '#include "spu_core.h"', '']
    lines += [f'void {name}(spu_t *s);' for _, name in table]
    lines += ['typedef struct { uint32_t elf; void (*fn)(spu_t *); } spu_prog_t;', 'const spu_prog_t spu_progs[] = {']
    lines += [f'  {{0x{va:08x}, {name}}},' for va, name in table]
    lines += ['};', f'const int spu_nprogs = {len(table)};', '']
    open(os.path.join(outdir, 'spu_progs.c'), 'w').write('\n'.join(lines))
    print(f'{len(table)} SPU programs compiled: ' + ', '.join(f'0x{va:08x}' for va, _ in table))


if __name__ == '__main__':
    main()
