"""Ahead-of-time compiler for the SPU programs embedded in the EBOOT.

Each program becomes one C function: every instruction gets a label and a call
`spu_exec(s, <word>, <pc>)` (spu_core.h, always inlined), so Clang constant-folds the decoding. After
each instruction the generated code falls through if the PC moved on by 4, and otherwise re-dispatches
through a switch over all instruction addresses (branches, calls, returns). A PC outside the program
returns to the runner.

Programs:
- SPURS task ELFs (machine 0x17) found in the EBOOT, named by their guest address: the executable
  segments at their ELF load addresses.
- SPURS job binaries ("jobbin2"), named `job:<guest address>:<size>`: position-independent code that
  spu_run_job (spu.c) loads at LS 0x1000 (JOB_BIN).

Output: out/spu_p_<addr>.c per program and out/spu_progs.c with the table {guest address, function}.

Usage: python -I spu2c.py <EBOOT.elf> <out dir> [elf_va_hex | job:va_hex:size_hex ...]   (default: the
skin/morph tasks and the Wwise audio jobs)"""
import os
import struct
import sys

JOB_BIN = 0x1000
DEFAULT = ['f18580', 'f19e80', 'f1b680', 'f1d880',
           # qTask programs run in place of their PPU versions (SceneModel, OcclusionCull, KartTrackScene, TrackView)
           'f00480', 'f1f180', 'efb380', 'eec980', 'f0d880', 'ef5100', 'edd680', 'f38780', 'f2e400', 'f28180',
           # Wwise jobs seen in the first race (binary address : size in bytes)
           'job:e51a00:490', 'job:e51100:110', 'job:e70500:4c10', 'job:e67c00:88a0', 'job:e54a00:1b10',
           'job:e52d00:910', 'job:e54180:810', 'job:e7b100:f10', 'job:e58a00:1f10', 'job:e66200:1990',
           'job:e5e100:2610', 'job:e7a800:890', 'job:e64a80:1710', 'job:e75180:4590']


def segments(d):
    phoff, = struct.unpack_from('>Q', d, 0x20)
    phnum, = struct.unpack_from('>H', d, 0x38)
    for i in range(phnum):
        t, fl, off, va, pa, fs, ms, al = struct.unpack_from('>IIQQQQQQ', d, phoff + i * 0x38)
        if t == 1:
            yield off, va, fs


def file_offset(d, va):
    for off, sva, fs in segments(d):
        if sva <= va < sva + fs:
            return off + va - sva
    raise ValueError(f'0x{va:x} is not in a loadable segment')


def elf_insns(d, foff):
    e_phoff, = struct.unpack_from('>I', d, foff + 0x1C)
    e_phnum, = struct.unpack_from('>H', d, foff + 0x2C)
    insns = []
    for i in range(e_phnum):
        t, off, va, pa, fsz, msz, fl, al = struct.unpack_from('>8I', d, foff + e_phoff + i * 32)
        if t != 1 or not (fl & 1):
            continue
        for a in range(0, fsz & ~3, 4):
            insns.append((va + a, struct.unpack_from('>I', d, foff + off + a)[0]))
    return insns


RRR_OP4 = {0x8, 0xB, 0xC, 0xD, 0xE, 0xF}
RI18_RT_ONLY = {0x08, 0x09, 0x21}                                    # hbra, hbrr, ila (op7)
REL_BRANCH = {0x40, 0x42, 0x44, 0x46, 0x64, 0x66}                    # brz brnz brhz brhnz br brsl (op9)
ABS_BRANCH = {0x60, 0x62}                                            # bra brasl
ENDS_BLOCK_OP11 = {0x1A8, 0x1A9, 0x1AA, 0x1AB, 0x128, 0x129, 0x12A, 0x12B, 0x000, 0x140}   # bi* (indirect), stop, stopd
MAX_BLOCK = 48


def regs(w):
    """Every register an instruction could touch: all of its 7-bit register fields (a superset is always safe)."""
    if w >> 28 in RRR_OP4:
        return {w & 0x7F, (w >> 7) & 0x7F, (w >> 14) & 0x7F, (w >> 21) & 0x7F}
    if w >> 25 in RI18_RT_ONLY:
        return {w & 0x7F}
    return {w & 0x7F, (w >> 7) & 0x7F, (w >> 14) & 0x7F}


def branch_target(pc, w):
    i16 = (w >> 7) & 0xFFFF
    i16 -= (i16 & 0x8000) << 1
    if w >> 23 in REL_BRANCH: return (pc + i16 * 4) & 0x3FFFF
    if w >> 23 in ABS_BRANCH: return (i16 * 4) & 0x3FFFF
    return None


def emit_per_insn(name, insns):
    # One label and spu_exec call per instruction, registers in *s; after each, fall through if the PC moved on
    # by 4, otherwise re-dispatch through the switch.
    lines = ['/* Generated by spu2c.py */', '#include "spu_core.h"', '#pragma clang diagnostic ignored "-Wunused-label"', '',
             f'void {name}(spu_t *s) {{', '  for (;;) {', '    switch (s->pc) {']
    lines += [f'    case 0x{pc:x}: goto L_{pc:x};' for pc, _ in insns]
    lines += ['    default: return;', '    }']
    for k, (pc, w) in enumerate(insns):
        nxt = insns[k + 1][0] if k + 1 < len(insns) else None
        fall = f'if (s->pc != 0x{nxt:x}) continue;' if nxt is not None else 'continue;'
        lines.append(f'L_{pc:x}: if (!spu_exec(s, 0x{w:08x}u, 0x{pc:x})) return; {fall}')
    lines += ['  }', '}', '']
    return '\n'.join(lines)


def emit(name, insns):
    # Straight-line blocks. A block copies the registers its instructions name into a local array, runs them,
    # and writes them back when it leaves, so the compiler keeps them in CPU registers inside the block (see
    # spu_exec_r in spu_core.h). After every instruction the next PC is checked (for all but branches it is a
    # constant and the check folds away), so a branch the block split missed still leaves the block correctly.
    # Blocks start at the program start, at branch targets and after branches; any other PC (an indirect jump
    # into the middle of a block) runs instruction by instruction from local store. A PC outside the program
    # returns to the runner.
    addrs = {pc for pc, _ in insns}
    leaders = {insns[0][0]}
    for k, (pc, w) in enumerate(insns):
        t = branch_target(pc, w)
        if t is not None and t in addrs: leaders.add(t)
        if (t is not None or w >> 21 in ENDS_BLOCK_OP11) and k + 1 < len(insns): leaders.add(insns[k + 1][0])
    blocks, cur = [], []
    for k, (pc, w) in enumerate(insns):
        if cur and (pc in leaders or len(cur) >= MAX_BLOCK or pc != cur[-1][0] + 4):
            blocks.append(cur); cur = []
        cur.append((pc, w))
    if cur: blocks.append(cur)
    lo, hi = insns[0][0], insns[-1][0] + 4
    lines = ['/* Generated by spu2c.py */', '#include "spu_core.h"', '#pragma clang diagnostic ignored "-Wunused-label"', '',
             f'void {name}(spu_t *s) {{', '  for (;;) {', '    switch (s->pc) {']
    lines += [f'    case 0x{b[0][0]:x}: goto L_{b[0][0]:x};' for b in blocks]
    lines += ['    default:',
              f'      if (s->pc < 0x{lo:x}u || s->pc >= 0x{hi:x}u) return;',
              '      if (!spu_exec(s, rd32(s, s->pc), s->pc)) return;',
              '      continue;', '    }']
    for bi, b in enumerate(blocks):
        used = sorted(set().union(*(regs(w) for _, w in b)))
        load = ' '.join(f'rf[{r}] = s->r[{r}];' for r in used)
        wb = ' '.join(f's->r[{r}] = rf[{r}];' for r in used)
        nxt = blocks[bi + 1][0][0] if bi + 1 < len(blocks) else None
        lines.append(f'L_{b[0][0]:x}: {{')
        lines.append(f'    q_t rf[128]; uint32_t npc; {load}')
        for k, (pc, w) in enumerate(b):
            lines.append(f'    if (!spu_exec_r(s, rf, &npc, 0x{w:08x}u, 0x{pc:x})) {{ {wb} s->pc = 0x{pc:x}; return; }}')
            if k + 1 < len(b):
                lines.append(f'    if (npc != 0x{pc + 4:x}) {{ {wb} s->pc = npc; continue; }}')
        go = f'if (npc == 0x{nxt:x}) goto L_{nxt:x}; ' if nxt is not None else ''
        lines.append(f'    {wb} s->pc = npc; {go}continue;')
        lines.append('  }')
    lines += ['  }', '}', '']
    return '\n'.join(lines)


def main():
    eboot, outdir = sys.argv[1], sys.argv[2]
    d = open(eboot, 'rb').read()
    table = []
    for spec in sys.argv[3:] or DEFAULT:
        if spec.startswith('job:'):
            _, va, size = spec.split(':')
            va, size = int(va, 16), int(size, 16)
            off = file_offset(d, va)
            insns = [(JOB_BIN + a, struct.unpack_from('>I', d, off + a)[0]) for a in range(0, size & ~3, 4)]
        else:
            va = int(spec, 16)
            off = file_offset(d, va)
            if d[off:off + 4] != b'\x7fELF' or struct.unpack_from('>H', d, off + 0x12)[0] != 0x17:
                raise ValueError(f'no SPU ELF at 0x{va:x}')
            insns = elf_insns(d, off)
        name = f'spu_prog_{va:08x}'
        path = os.path.join(outdir, f'spu_p_{va:08x}.c')
        # block code for the SPURS jobs (Wwise's audio renderer: checked against the interpreter with MNR_SPU_VERIFY);
        # the task ELFs keep one dispatch per instruction until they are checked the same way
        src = emit(name, insns) if spec.startswith('job:') else emit_per_insn(name, insns)
        if not os.path.exists(path) or open(path).read() != src:   # keep the mtime when unchanged
            open(path, 'w').write(src)
        table.append((va, name, insns[0][0], insns[-1][0] + 4))
    lines = ['/* Generated by spu2c.py: SPU programs compiled ahead of time (see spu_core.h). */', '#include "spu_core.h"', '']
    lines += [f'void {name}(spu_t *s);' for _, name, _, _ in table]
    lines += ['typedef struct { uint32_t elf; void (*fn)(spu_t *); uint32_t lo, hi; } spu_prog_t;', 'const spu_prog_t spu_progs[] = {']
    lines += [f'  {{0x{va:08x}, {name}, 0x{lo:x}, 0x{hi:x}}},' for va, name, lo, hi in table]
    lines += ['};', f'const int spu_nprogs = {len(table)};', '']
    open(os.path.join(outdir, 'spu_progs.c'), 'w').write('\n'.join(lines))
    print(f'{len(table)} SPU programs compiled: ' + ', '.join(f'0x{va:08x}' for va, *_ in table))


if __name__ == '__main__':
    main()
